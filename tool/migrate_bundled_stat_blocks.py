#!/usr/bin/env python3
"""Idempotent generator for Cleanup slice 18 Step 5 (Fixes 5.1 & 5.2).

Migrates bundled bestiary and summon preset files from app `MinionStatBlock`
to ruleset `MonsterStatBlock`, removes `accentColor:` / `accentArgb:` arguments
from the data files, and generates
`lib/models/monster_codex/monster_presentation_registry.dart` keyed by stat
block id.

Idempotent: running a second time produces byte-identical files across every
data file and the generated presentation registry.
"""

import glob
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "lib/models/monster_codex/monster_presentation_registry.dart"

DATA_GLOBS = [
    "lib/models/monster_codex/bestiary/*.dart",
    "lib/models/srd_summons/spells/*.dart",
    "lib/models/srd_summons/magic_items/*.dart",
]

ID_RE = re.compile(r"\bid:\s*'([^']+)'")
ACCENT_LINE_RE = re.compile(
    r"^[ \t]*accent(?:Color|Argb):\s*(?:const\s+)?Argb\((0x[0-9A-Fa-f]+)\),?[ \t]*\r?\n",
    re.MULTILINE,
)
EXISTING_REG_ENTRY_RE = re.compile(r"^\s*'([^']+)':\s*Argb\((0x[0-9A-Fa-f]+)\),", re.MULTILINE)


def load_existing_registry() -> dict[str, str]:
    if not REGISTRY_PATH.exists():
        return {}
    text = REGISTRY_PATH.read_text(encoding="utf-8")
    return {m.group(1): m.group(2) for m in EXISTING_REG_ENTRY_RE.finditer(text)}


def extract_accent_by_id(text: str) -> dict[str, str]:
    """Extract (stat_block_id -> Argb hex) from MinionStatBlock / MonsterStatBlock calls."""
    found: dict[str, str] = {}
    ctor_re = re.compile(r"\b(?:MinionStatBlock|MonsterStatBlock)\(")
    starts = [m.start() for m in ctor_re.finditer(text)]
    for idx, start in enumerate(starts):
        end = starts[idx + 1] if idx + 1 < len(starts) else len(text)
        chunk = text[start:end]
        m_id = ID_RE.search(chunk)
        m_acc = ACCENT_LINE_RE.search(chunk)
        if m_id and m_acc:
            sid = m_id.group(1)
            hex_val = m_acc.group(1)
            if sid in found and found[sid] != hex_val:
                raise RuntimeError(
                    f"Conflicting accentArgb for stat block id '{sid}': "
                    f"{found[sid]} vs {hex_val}"
                )
            found[sid] = hex_val
    return found


def render_registry(entries: dict[str, str]) -> str:
    lines = [
        "// GENERATED BY tool/migrate_bundled_stat_blocks.py — DO NOT EDIT BY HAND.",
        "import '../visual/argb.dart';",
        "",
        "/// Visual accent color registry attached to bundled monster and summon",
        "/// stat blocks by stat block id.",
        "const Map<String, Argb> kBundledMonsterAccentArgb = {",
    ]
    for sid in sorted(entries):
        lines.append(f"  '{sid}': Argb({entries[sid]}),")
    lines.extend(
        [
            "};",
            "",
            "/// Resolves the accent color for a monster stat block by [id], falling back",
            "/// to the homebrew creature-type palette when [id] is not in the bundled table.",
            "Argb resolveMonsterAccentArgb({",
            "  required String id,",
            "  required String typeDisplay,",
            "}) {",
            "  final bundled = kBundledMonsterAccentArgb[id];",
            "  if (bundled != null) return bundled;",
            "  final typeLower = typeDisplay.toLowerCase();",
            "  if (typeLower.contains('beast')) return const Argb(0xFF388E3C);",
            "  if (typeLower.contains('dragon')) return const Argb(0xFFFF8F00);",
            "  if (typeLower.contains('fiend')) return const Argb(0xFFC62828);",
            "  if (typeLower.contains('undead')) return const Argb(0xFF7B1FA2);",
            "  if (typeLower.contains('elemental')) return const Argb(0xFFE65100);",
            "  if (typeLower.contains('fey')) return const Argb(0xFF00897B);",
            "  if (typeLower.contains('celestial')) return const Argb(0xFF0288D1);",
            "  if (typeLower.contains('construct')) return const Argb(0xFF5D4037);",
            "  if (typeLower.contains('aberration')) return const Argb(0xFF6A1B9A);",
            "  return const Argb(0xFF8B5CF6);",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    files: list[Path] = []
    for pattern in DATA_GLOBS:
        files.extend(sorted(Path(p) for p in glob.glob(str(ROOT / pattern))))

    accent_map = load_existing_registry()
    changed_files = 0
    total_ctor_renames = 0
    total_accent_removals = 0

    for path in files:
        original = path.read_text(encoding="utf-8")
        extracted = extract_accent_by_id(original)
        for sid, hex_val in extracted.items():
            if sid in accent_map and accent_map[sid] != hex_val:
                raise RuntimeError(
                    f"Registry conflict for '{sid}': {accent_map[sid]} vs {hex_val}"
                )
            accent_map[sid] = hex_val

        updated, ctor_count = re.subn(r"\bMinionStatBlock\b", "MonsterStatBlock", original)
        updated, acc_count = ACCENT_LINE_RE.subn("", updated)
        total_ctor_renames += ctor_count
        total_accent_removals += acc_count

        if updated != original:
            path.write_text(updated, encoding="utf-8")
            changed_files += 1

    registry_text = render_registry(accent_map)
    reg_changed = (
        not REGISTRY_PATH.exists()
        or REGISTRY_PATH.read_text(encoding="utf-8") != registry_text
    )
    if reg_changed:
        REGISTRY_PATH.write_text(registry_text, encoding="utf-8")

    print(
        f"migrate_bundled_stat_blocks: scanned={len(files)} "
        f"changed_data_files={changed_files} ctor_renames={total_ctor_renames} "
        f"accent_removals={total_accent_removals} "
        f"registry_entries={len(accent_map)} registry_changed={reg_changed}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
